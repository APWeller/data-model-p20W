def file_of(table) -> str:
    """CEDARS file letter a fact is built from (from its school_year_sk element)."""
    for c in table.cols:
        if c.name == "school_year_sk" and c.elems and c.elems[0].isalpha():
            return c.elems[0]
    return ""


def role_element(letter: str, role: str) -> str:
    """The file's element playing a role: @ssid or @district."""
    for e in active(letter):
        name = e["element_name"]
        if role == "@ssid" and "SSID" in name:
            return e["element_id"]
        if role == "@district" and "County District Code" in name and "Home" not in name:
            return e["element_id"]
    raise KeyError((letter, role))


def resolve_elems(elems: str, letter: str) -> list[str]:
    out = []
    for e in filter(None, elems.split(",")):
        e = e.strip()
        if e.startswith("@"):
            e = role_element(letter, e)
        elif e.startswith("*"):
            e = (letter + e[1:]) if letter else e
        if e not in out:
            out.append(e)
    return out


def gold_comment(c, letter) -> str:
    ids = resolve_elems(c.elems, letter)
    if c.desc.startswith(("Load metadata", "Surrogate key", "SCD2:")):
        return c.desc
    if not ids:
        return c.desc if c.desc.startswith("Derived") else f"Derived: {c.desc}"
    shown = ", ".join(i if not i.startswith("*") else f"{i} (all files)" for i in ids)
    desc = c.desc[len("Derived: "):] if c.desc.startswith("Derived: ") else c.desc
    prefix = "Derived from CEDARS" if c.desc.startswith("Derived") else "CEDARS"
    return f"{prefix} {shown} – {desc}"


GOLD_LINEAGE: list[dict] = []


def gen_gold():
    for t in GOLD.values():
        letter = file_of(t)
        cols, fks = [], []
        for c in t.cols:
            nn = c.nn or c.name in t.pk
            cols.append(column(c.name, c.type, gold_comment(c, letter), nn))
            if c.fk:
                fks.append(f"  CONSTRAINT {t.name}_{c.name}_fk FOREIGN KEY ({c.name}) "
                           f"REFERENCES {CAT}.gold.{c.fk[0]} ({c.fk[1]})")
            GOLD_LINEAGE.append({"gold_table": t.name, "gold_column": c.name, "type": c.type,
                                 "element_ids": ",".join(resolve_elems(c.elems, letter)), "description": c.desc,
                                 "fk_table": c.fk[0] if c.fk else ""})
        props = {"cedars.manual_version": MANUAL_VERSION, "cedars.table_kind": t.kind}
        if t.restricted:
            props["cedars.restricted"] = "true"
        if t.extra.get("code_sets"):
            props["cedars.code_sets"] = ",".join(t.extra["code_sets"])
        sql = create_table(f"{CAT}.gold.{t.name}", cols + fks, comment=t.comment, pk=t.pk, cluster=t.cluster,
                           props=props)
        write(SQL / "gold" / f"{t.name}.sql", sql)
    for name, body in VIEWS.items():
        write(SQL / "gold" / "views" / f"{name}.sql", f"CREATE OR REPLACE VIEW {CAT}.gold.{name} AS\n{body};\n")
    gen_special_members()


def gen_special_members():
    stmts = []
    for t in GOLD.values():
        if t.kind not in ("dim", "junk") or not t.special_members:
            continue
        key = t.pk[0]
        # Label only a descriptive column; never a natural key or code.
        names = [c.name for c in t.cols]
        label = next((n for n in ("description", "school_year_label", "district_name", "school_name",
                                  "grade_level_description", "program_name", "state_course_name", "group_codes",
                                  "course_title", "day_name") if n in names), None)
        members = [(-1, "Unknown"), (-2, "Not applicable")]
        extra = {}
        if t.name == "dim_school":
            members.append((-3, "Out-of-district school"))
            extra = {-3: {"school_code": "'9999'", "is_out_of_district": "true"}}
        cols = [key] + ([label] if label else [])
        if t.scd2:
            cols += ["effective_from", "effective_to", "is_current"]
        if t.name == "dim_school":
            cols += ["school_code", "is_out_of_district"]
        if any(c.name == "member_count" for c in t.cols):
            cols += ["member_count"]
        cols += ["_manual_version"]
        rows = []
        for skv, lab in members:
            v = [str(skv)] + ([f"'{lab}'"] if label else [])
            if t.scd2:
                v += ["DATE'1900-01-01'", "DATE'9999-12-31'", "true"]
            if t.name == "dim_school":
                v += [extra.get(skv, {}).get("school_code", "NULL"), extra.get(skv, {}).get("is_out_of_district", "false")]
            if "member_count" in cols:
                v += ["0"]
            v += [f"'{MANUAL_VERSION}'"]
            rows.append("(" + ", ".join(v) + ")")
        fqn = f"{CAT}.gold.{t.name}"
        stmts.append(
            f"INSERT INTO {fqn} ({', '.join(cols)})\nSELECT {', '.join('s.' + c for c in cols)}\n"
            f"FROM VALUES\n  " + ",\n  ".join(rows) + f"\n  AS s({', '.join(cols)})\n"
            f"WHERE NOT EXISTS (SELECT 1 FROM {fqn} AS t WHERE t.{key} = s.{key});\n")
    write(SQL / "gold" / "special_members.sql", "\n".join(stmts))


def deploy_order() -> list[str]:
    order = ["00_schemas.sql"] + [f"ref/{p.name}" for p in sorted((SQL / "ref").glob("*.sql"))]
    order += [f"bronze/{p.name}" for p in sorted((SQL / "bronze").glob("*.sql"))]
    order += [f"silver/{p.name}" for p in sorted((SQL / "silver").glob("*.sql"))]
    done: list[str] = []

    def visit(name, stack=()):
        if name in done:
            return
        if name in stack:
            return  # dim_date <-> dim_school_year: FK targets are created first by name order below
        for c in GOLD[name].cols:
            if c.fk and c.fk[0] != name:
                visit(c.fk[0], stack + (name,))
        done.append(name)
    visit("dim_school_year")
    for n in GOLD:
        visit(n)
    order += [f"gold/{n}.sql" for n in done] + ["gold/special_members.sql"]
    order += [f"gold/views/{v}.sql" for v in VIEWS]
    return order


