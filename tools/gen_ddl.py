def gen_schemas():
    sql = ""
    for s, c in [("bronze", "CEDARS files as received: all columns STRING, plus load metadata"),
                 ("silver", "Typed, validated, crosswalked CEDARS entities"),
                 ("ref", "CEDARS code sets (appendices and inline valid values)"),
                 ("gold", "CEDARS Kimball star schema")]:
        sql += f"CREATE SCHEMA IF NOT EXISTS {CAT}.{s} COMMENT '{q(c)}';\n"
    write(SQL / "00_schemas.sql", sql)


def gen_bronze():
    for code, spec in FILES.items():
        f = FILES_CSV[code]
        cols = [column(e["field_name"], "STRING", f"CEDARS {e['element_id']} – {e['element_name']} (as received)")
                for e in active(code)]
        cols.append(column("_rescued_data", "STRING", "Load metadata: columns that did not match the file layout"))
        cols += meta_cols(BRONZE_META, not_null=())
        sql = create_table(f"{CAT}.bronze.{spec['table']}", cols,
                           comment=f"CEDARS File {code} – {f['file_title']} ({f['file_name']}), as received",
                           cluster=["_school_year", "_submission_type"],
                           props={"cedars.file_code": code, "cedars.manual_version": MANUAL_VERSION})
        write(SQL / "bronze" / f"{spec['table']}.sql", sql)


