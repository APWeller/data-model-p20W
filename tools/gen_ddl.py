def q(s: str) -> str:
    """Escape a Databricks SQL string literal (backslash escapes; '' is not an escape in Spark SQL)."""
    return s.replace("\\", "\\\\").replace("'", "\\'")


def snake(s: str) -> str:
    s = s.replace("’", "").replace("'", "").replace("&", " and ").replace("/", " ").replace("+", " plus ")
    s = re.sub(r"\(.*?\)", " ", s)
    return re.sub(r"[^A-Za-z0-9]+", "_", s).strip("_").lower()


def col_name(eid: str) -> str:
    if eid in NAMES:
        return NAMES[eid]
    name = ELEMENTS[eid]["element_name"]
    if name == "School Year":
        return "school_year"
    if "County District Code" in name and "Home" not in name:
        return "county_district_code"
    if name == "District Student ID":
        return "district_student_id"
    if "SSID" in name:
        return "ssid"
    return snake(name)


def col_type(eid: str) -> str:
    e = ELEMENTS[eid]
    if e["is_multi_valued"] == "Y":
        return "ARRAY<STRING>"
    if eid in TYPE_OVERRIDES:
        return TYPE_OVERRIDES[eid]
    if eid in CODED or e["inline_valid_values"]:
        return "STRING"  # codes stay strings so they join to ref.ref_code without losing zeros (D-028)
    dt, size = e["data_type"], e["size"]
    if dt == "date":
        return "DATE"
    if dt == "char" and size == "4" and "Year" in e["element_name"]:
        return "INT"
    if dt == "int":
        return "INT"
    if dt == "numeric":
        p, _, s = size.partition(",")
        return f"DECIMAL({p},{s or 0})"
    return "STRING"


def comment_for(eid: str, suffix: str = "") -> str:
    e = ELEMENTS[eid]
    text = f"CEDARS {eid} – {e['element_name']}"
    cs = CODE_SET_OF.get(eid)
    if cs:
        text += f" [code set: {', '.join(cs)}]"
    return text + suffix


def column(name, typ, comment, not_null=False):
    nn = " NOT NULL" if not_null else ""
    return f"  {name} {typ}{nn} COMMENT '{q(comment)}'"


def create_table(fqn, cols, *, comment, pk=None, cluster=None, props=None):
    body = list(cols)
    if pk:
        cname = fqn.split(".")[-1] + "_pk"
        body.append(f"  CONSTRAINT {cname} PRIMARY KEY ({', '.join(pk)})")
    sql = f"CREATE TABLE IF NOT EXISTS {fqn} (\n" + ",\n".join(body) + "\n)\nUSING DELTA"
    if cluster:
        sql += f"\nCLUSTER BY ({', '.join(cluster)})"
    sql += f"\nCOMMENT '{q(comment)}'"
    if props:
        sql += "\nTBLPROPERTIES (\n" + ",\n".join(f"  '{k}' = '{q(v)}'" for k, v in props.items()) + "\n)"
    return sql + ";\n"


def write(path: Path, sql: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    header = f"-- Generated by tools/gen_ddl.py from the CEDARS catalog (manual v{MANUAL_VERSION}). Do not edit.\n"
    path.write_text(header + sql)


BRONZE_META = [
    ("_source_file", "STRING", "Load metadata: submitted file name"),
    ("_school_year", "INT", "Load metadata: school year of the submission (ending year, e.g. 2027)"),
    ("_manual_version", "STRING", "Load metadata: CEDARS manual version the file conforms to (backload seam)"),
    ("_submission_type", "STRING", "Load metadata: submission type (e.g. year-end final)"),
    ("_load_ts", "TIMESTAMP", "Load metadata: load timestamp"),
]
SILVER_META = BRONZE_META + [
    ("_record_hash", "STRING", "Load metadata: hash of the typed business columns, for change detection"),
    ("_dq_issues", "ARRAY<STRING>", "Load metadata: IDs of failed non-rejecting checks: IR### (catalog/integrity_rules.csv) "
                                    "or DQ### (docs/silver-contract.md)"),
]


def meta_cols(meta, not_null=("_manual_version", "_submission_type")):
    return [column(n, t, c, n in not_null) for n, t, c in meta]


def active(file_code):
    return [e for e in ELEMENTS.values() if e["file_code"] == file_code and e["is_active"] == "Y"]


