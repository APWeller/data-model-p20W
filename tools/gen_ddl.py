"""Generate bronze, ref and silver DDL from the catalog.

Usage:  .venv/bin/python tools/gen_ddl.py

Outputs
  sql/00_schemas.sql
  sql/bronze/<table>.sql      files as received: every column STRING + load metadata
  sql/ref/<table>.sql         code-set registry and codes (loaded from seeds/ref)
  sql/silver/<table>.sql      typed entity per CEDARS file, crosswalks, attribute history
  sql/gold/<table>.sql        star schema (tools/gold_spec.py), incl. FK constraints
  sql/gold/views/<view>.sql   BI helper views
  sql/gold/special_members.sql  -1 unknown / -2 not applicable (and -3 school 9999) rows
  sql/deploy_order.txt        file order satisfying FK dependencies
  catalog/silver_columns.csv  element -> silver table.column lineage (input to phase 5)
  catalog/gold_columns.csv    gold table.column -> element IDs (input to phase 5)
  docs/erd.md                 Mermaid ERD, one diagram per fact family

The catalog name is parameterized as ${catalog}.
"""

from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gold_spec import FAMILIES, TABLES as GOLD, VIEWS  # noqa: E402
from silver_spec import (DERIVED, FILES, LOCATION_ELEMENT, NAMES, STUDENT_ATTRIBUTES,  # noqa: E402
                         STUDENT_PII_ATTRIBUTES, TYPE_OVERRIDES)

REPO = Path(__file__).resolve().parents[1]
SQL = REPO / "sql"
CAT = "${catalog}"
MANUAL_VERSION = "19.0"


def load(path):
    with open(path, newline="") as fh:
        return list(csv.DictReader(fh))


ELEMENTS = {r["element_id"]: r for r in load(REPO / "catalog" / "elements.csv")}
FILES_CSV = {r["file_code"]: r for r in load(REPO / "catalog" / "files.csv")}
CODE_SETS = load(REPO / "catalog" / "code_sets.csv")
CODED = {e for r in CODE_SETS for e in filter(None, r["referenced_by"].split(","))}
CODE_SET_OF = {}
for r in CODE_SETS:
    for e in filter(None, r["used_by"].split(",")):
        CODE_SET_OF.setdefault(e, []).append(r["code_set"])


