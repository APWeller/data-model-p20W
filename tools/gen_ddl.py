def gen_erd():
    out = ["# CEDARS gold ERD", "",
           "Generated by `tools/gen_ddl.py` from `tools/gold_spec.py`. One diagram per fact family: each "
           "fact with the dimensions it references, and the bridges that hang off those dimensions. "
           "Only key and foreign-key columns are shown. Standard dimensions (date, school year, district, "
           "school, student) appear in every family. Full column lists are in `sql/gold/`.", ""]
    for fam, title in FAMILIES.items():
        facts = [t for t in GOLD.values() if t.kind == "fact" and t.family == fam]
        tables = {t.name for t in facts}
        for f in facts:
            tables |= {c.fk[0] for c in f.cols if c.fk}
        # bridges attached to any table in the diagram, plus their member dims
        for b in GOLD.values():
            if b.kind == "bridge" and any(c.fk and c.fk[0] in tables for c in b.cols) and \
                    (b.family in ("", fam) or b.family == fam):
                if b.family and b.family != fam:
                    continue
                tables.add(b.name)
                tables |= {c.fk[0] for c in b.cols if c.fk}
        rels = []
        for n in sorted(tables):
            for c in GOLD[n].cols:
                if c.fk and c.fk[0] in tables and n != c.fk[0]:
                    label = c.name.removesuffix("_sk")
                    rels.append(f"    {c.fk[0]} ||--o{{ {n} : \"{label}\"")
        out += [f"## {title}", "", "Facts: " + ", ".join(f"`{f.name}`" for f in facts), "", "```mermaid",
                "erDiagram"]
        for n in sorted(tables, key=lambda x: (GOLD[x].kind != "fact", x)):
            t = GOLD[n]
            out.append(f"    {n} {{")
            for c in t.cols:
                if c.name in t.pk or c.fk:
                    tag = " PK" if c.name in t.pk else ""
                    tag += (", FK" if tag else " FK") if c.fk else ""
                    typ = re.sub(r"[^A-Za-z0-9_]", "_", c.type.split("(")[0]).lower()
                    out.append(f"        {typ} {c.name}{tag}")
            out.append("    }")
        out += sorted(set(rels)) + ["```", ""]
    (REPO / "docs" / "erd.md").write_text("\n".join(out))


