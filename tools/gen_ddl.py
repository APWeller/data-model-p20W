LINEAGE: list[dict] = []


def lineage(eid, table, col, how):
    LINEAGE.append({"element_id": eid, "silver_table": table, "silver_column": col, "transformation": how})


def gen_silver_entity(code, spec):
    f = FILES_CSV[code]
    table = spec["table"]
    key_ids = [k for k in spec["key"] if k in ELEMENTS]
    cols, names = [], {}
    for e in active(code):
        eid = e["element_id"]
        name = col_name(eid)
        typ = col_type(eid)
        pii = " [PII]" if eid in spec.get("pii", []) else ""
        if typ.startswith("ARRAY"):
            enc = e["multi_value_encoding"]
            how = "split into single characters" if enc == "concatenated" else "split on comma, trimmed"
            cols.append(column(name, typ, comment_for(eid, f" ({how})")))
            cols.append(column(f"{name}_raw", "STRING", comment_for(eid, " (as reported)")))
            lineage(eid, table, name, f"multi-valued: {how}")
            lineage(eid, table, f"{name}_raw", "as reported")
        else:
            cols.append(column(name, typ, comment_for(eid, pii), eid in key_ids))
            lineage(eid, table, name, f"cast to {typ}" if typ != "STRING" else "trimmed; blank -> NULL")
        names[eid] = name
        if code in LOCATION_ELEMENT and eid == LOCATION_ELEMENT[code]:
            cols.append(column("school_code", "STRING",
                               f"Derived: CEDARS A05 resolved from {eid} via silver.xref_location "
                               f"(school year + district + Location ID)"))
    for name, typ, nn, cmt in DERIVED.get(code, []):
        cols.append(column(name, typ, cmt, nn))
    cols += meta_cols(SILVER_META)
    pk = [names.get(k, k) for k in spec["key"]] + ["_submission_type"]
    props = {"cedars.file_code": code, "cedars.manual_version": MANUAL_VERSION}
    if spec.get("pii"):
        props["cedars.pii_columns"] = ",".join(names[e] for e in spec["pii"])
    sql = create_table(f"{CAT}.silver.{table}", cols,
                       comment=f"CEDARS File {code} – {f['file_title']}. Grain: {f['stated_grain']}",
                       pk=pk, cluster=["school_year", "county_district_code"], props=props)
    write(SQL / "silver" / f"{table}.sql", sql)


