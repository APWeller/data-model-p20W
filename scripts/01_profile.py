"""Step 1: profile allDataElements.csv and write outputs/profile.md.

Read-only on the input. Re-run: python3 scripts/01_profile.py
"""
from pathlib import Path
import re

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "allDataElements.csv"
OUT = ROOT / "outputs"
OUT.mkdir(exist_ok=True)

ID_PATTERN = re.compile(
    r"\b(?:id|ids|identifier|key|code|cd|number|num|no|nbr|ssn|ssid|sid|"
    r"ein|ubi|fein|ipeds|opeid|cip|soc|naics)\b",
    re.IGNORECASE,
)


def to_md(df: pd.DataFrame, index: bool = True) -> str:
    """Minimal markdown table (avoids a tabulate dependency)."""
    if index:
        df = df.reset_index()
    esc = lambda v: str(v).replace("|", "\\|").replace("\n", " ").replace("\r", " ")
    head = "| " + " | ".join(esc(c) for c in df.columns) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    body = ["| " + " | ".join(esc(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([head, sep, *body])


def load() -> pd.DataFrame:
    # keep_default_na=False so blank stays "" and literal "NA" is visible as a value
    return pd.read_csv(SRC, encoding="utf-8-sig", dtype=str, keep_default_na=False)


def md_table(s: pd.Series, name: str, count: str = "rows") -> str:
    df = s.rename(count).reset_index()
    df.columns = [name, count]
    return to_md(df, index=False)


def pk_class(v: str) -> str:
    v2 = v.strip()
    if v2.lower() in ("x", "y"):
        return "flagged PK"
    if v2 == "?":
        return "uncertain"
    if v2 == "":
        return "unknown (blank)"
    return f"other: {v2!r}"


def main() -> None:
    df = load()
    lines: list[str] = []
    w = lines.append

    w("# Profile: allDataElements.csv\n")
    w("Generated by `scripts/01_profile.py`. Input is read-only.\n")
    w(f"- Rows: **{len(df):,}**")
    w(f"- Columns ({len(df.columns)}): {', '.join(df.columns)}")
    rn = pd.to_numeric(df["Row #"], errors="coerce")
    w(f"- Row # range: {int(rn.min())}–{int(rn.max())}; "
      f"non-numeric: {rn.isna().sum()}; duplicates: {df['Row #'].duplicated().sum()}; "
      f"gaps: {int(rn.max() - rn.min() + 1 - rn.nunique())}")
    w("")

    # --- Key findings (computed; see detail sections below)
    pkc = df["Primary Key?"].map(pk_class).value_counts()
    tn = df["Table Name"].str.strip()
    ipeds_y = df[(df["Primary Key?"].str.strip() == "Y")]
    en0 = df["Data Element Name"]
    w("## Key findings\n")
    w(f"1. **{df['Sector Name'].nunique()} sectors, {df['Agency Name'].nunique()} agencies, "
      f"{df['Source or Program'].str.strip().nunique()} sources/programs, "
      f"{df.groupby(['Sector Name','Agency Name','Source or Program', tn]).ngroups} distinct tables.** "
      f"K-12 is {(df['Sector Name']=='K-12').mean():.0%} of rows; Workforce is "
      f"{(df['Sector Name']=='Workforce').sum()} rows (ESD only).")
    w(f"2. **PK flags:** flagged {pkc.get('flagged PK',0)}, uncertain {pkc.get('uncertain',0)}, "
      f"unknown/blank {pkc.get('unknown (blank)',0)}. "
      f"All {len(ipeds_y)} 'Y' flags are IPEDS/finance rows where nearly every element (including measures "
      f"like depreciation, EFTOTAL) is flagged. 'Y' there appears to mean something other than PK "
      f"(e.g. 'included'), so treat it as not evidence of a key.")
    w(f"3. **Blank/placeholder Table Name:** {tn.str.lower().isin(['','na','n/a']).sum()} rows "
      f"({(tn=='').sum()} blank + {tn.str.lower().isin(['na','n/a']).sum()} 'n/a'), "
      f"all Early Learning (Hist ECEAP blank; ELMS 'n/a').")
    w(f"4. **Dirty element names:** {((en0 != en0.str.strip()) | en0.str.contains(chr(9))).sum()} rows "
      f"with leading/trailing whitespace, tabs, or embedded newlines. Normalize with strip() before matching.")
    w(f"5. **Table Granularity** is populated on only "
      f"{(~df['Table Granularity'].str.strip().str.upper().isin(['','NA'])).sum()} rows, all DCYF. "
      f"Of those, 29 say 'multiple observations by childid', which is direct evidence for multi-active satellites.")
    w(f"6. **Governance** has {df['Governance Requirements'].str.strip().nunique()} categories. Several tables "
      f"mix categories (e.g. UI_Wage: A1 + NA for SSN/names), so splitting satellites by governance is needed.")
    w("7. **Year fields** mix yyyy, school-year, and Excel-coerced m/d/yyyy formats. "
      "Most Recent Year is blank on most rows.")
    w("8. **Same-named identifiers recur across agencies** (e.g. SSN in 7 tables across ESD, LNI, "
      "OFM/PCHEES, OSPI, SBCTC, WSAC; SSID across OSPI, DCYF, WSAC). Per the modeling rules these are "
      "treated as separate agency business keys, with cross-agency identity as same-as links.")
    w("9. **Surrogate/system keys are common** (DCYF ELMS *Id columns, SBCTC DW_KEY, NSC RecordID, "
      "AOC Case Key). These need business-key review in step 2.")
    w("10. **No FK/relationship metadata.** Every link will be inferred from shared element names and "
      "descriptions.")
    w("")

    # --- Blank / dirty values per column
    w("## Blank and dirty values by column\n")
    rows = []
    for c in df.columns:
        col = df[c]
        rows.append({
            "column": c,
            "blank": int((col.str.strip() == "").sum()),
            "literal NA/N/A": int(col.str.strip().str.upper().isin(["NA", "N/A"]).sum()),
            "leading/trailing ws": int((col != col.str.strip()).sum()),
            "contains tab": int(col.str.contains("\t").sum()),
            "contains newline": int(col.str.contains(r"[\r\n]").sum()),
            "distinct": col.nunique(),
        })
    w(to_md(pd.DataFrame(rows), index=False))
    w("")

    # --- Counts by dimension
    w("## Rows by Sector\n")
    w(md_table(df["Sector Name"].value_counts(), "Sector Name"))
    w("")
    w("## Rows by Sector × Agency\n")
    w(df.groupby(["Sector Name", "Agency Name"]).size().rename("rows")
      .reset_index().pipe(to_md, index=False))
    w("")
    w("## Rows by Dataset\n")
    w(md_table(df["Dataset"].value_counts(), "Dataset"))
    w("")
    w("## Rows by Source.Name (file)\n")
    w(md_table(df["Source.Name"].value_counts(), "Source.Name"))
    w("")
    w("## Rows by Sector × Source or Program\n")
    w(df.groupby(["Sector Name", "Source or Program"]).size().rename("rows")
      .reset_index().pipe(to_md, index=False))
    w("")

    # --- Tables
    w("## Tables\n")
    t = df.assign(tbl=df["Table Name"].str.strip().replace("", "(blank)"))
    tbl = (t.groupby(["Sector Name", "Agency Name", "Source or Program", "tbl"])
           .agg(elements=("Row #", "size"),
                pk_flagged=("Primary Key?", lambda s: s.str.strip().str.lower().isin(["x", "y"]).sum()),
                pk_uncertain=("Primary Key?", lambda s: (s.str.strip() == "?").sum()),
                first_year=("First Year Available", lambda s: ", ".join(sorted(set(v for v in s if v.strip()))[:3])),
                governance=("Governance Requirements", lambda s: "; ".join(sorted(set(v.strip() for v in s if v.strip())))))
           .reset_index().rename(columns={"tbl": "Table Name"}))
    w(f"Distinct (sector, agency, source, table) combinations: **{len(tbl)}**. "
      f"Tables with ≥1 flagged PK: **{(tbl.pk_flagged > 0).sum()}**; "
      f"with none flagged and none uncertain: **{((tbl.pk_flagged == 0) & (tbl.pk_uncertain == 0)).sum()}**.\n")
    w(to_md(tbl, index=False))
    w("")

    # --- Blank table names
    blank_t = df[df["Table Name"].str.strip().str.lower().isin(["", "na", "n/a"])]
    w(f"## Rows with blank or placeholder (NA, n/a) Table Name ({len(blank_t)})\n")
    w(blank_t.groupby(["Sector Name", "Agency Name", "Source or Program", "Source.Name"])
      .size().rename("rows").reset_index().pipe(to_md, index=False))
    w("")

    # --- PK flag
    w("## Primary Key? distribution\n")
    w("Raw values:\n")
    w(md_table(df["Primary Key?"].map(repr).value_counts(), "raw value (repr)"))
    w("")
    w("Classified (x/Y = flagged; ? = uncertain; blank = unknown, NOT 'not a key'):\n")
    w(df.assign(pk=df["Primary Key?"].map(pk_class))
      .groupby(["Sector Name", "pk"]).size().unstack(fill_value=0).pipe(to_md))
    w("")

    # --- Governance
    w("## Governance Requirements\n")
    w(df.assign(g=df["Governance Requirements"].str.strip().replace("", "(blank)"))
      .groupby(["g", "Sector Name"]).size().unstack(fill_value=0).pipe(to_md))
    w("")

    # --- Table Granularity
    w("## Table Granularity (non-blank, non-NA values)\n")
    g = df["Table Granularity"].str.strip()
    g = g[(g != "") & (g.str.upper() != "NA")]
    w(f"{len(g)} rows have a value.\n")
    if len(g):
        w(md_table(g.value_counts(), "Table Granularity"))
    w("")

    # --- Year value formats
    w("## First/Most Recent Year Available: value formats\n")
    w("Mixed formats. m/d/yyyy values look like Excel date coercion of the source "
      "spreadsheet (e.g. 2/1/1901, 7/16/1905 are implausible); treat these years as unreliable.\n")
    def year_fmt(v: str) -> str:
        v = v.strip()
        if v == "": return "blank"
        if re.fullmatch(r"\d{4}", v): return "yyyy"
        if re.fullmatch(r"\d{4}-\d{2}", v): return "yyyy-yy (school year)"
        if re.fullmatch(r"\d{4}-\d{4}", v): return "yyyy-yyyy"
        if re.fullmatch(r"\d{1,2}/\d{1,2}/\d{4}", v): return "m/d/yyyy (Excel date?)"
        return "other text"
    yf = pd.DataFrame({c: df[c].map(year_fmt).value_counts()
                       for c in ["First Year Available", "Most Recent Year Available"]}).fillna(0).astype(int)
    w(to_md(yf.rename_axis("format")))
    w("")

    # --- Dirty element names
    en = df["Data Element Name"]
    dirty = df[(en != en.str.strip()) | en.str.contains("\t") | (en.str.strip() == "")]
    w(f"## Dirty Data Element Names ({len(dirty)})\n")
    w("Leading/trailing whitespace, tabs, or blank. `repr` shown.\n")
    w(dirty.assign(name_repr=dirty["Data Element Name"].map(repr))
      [["Row #", "Sector Name", "Table Name", "name_repr"]].pipe(to_md, index=False))
    w("")

    # --- Duplicate elements within a table
    key = df.assign(t=df["Table Name"].str.strip(), e=df["Data Element Name"].str.strip().str.lower())
    dup = key[key.duplicated(["Sector Name", "Agency Name", "Source or Program", "t", "e"], keep=False)
              & (key.t != "")]
    w(f"## Duplicate element names within the same table ({len(dup)} rows)\n")
    if len(dup):
        w(dup[["Row #", "Sector Name", "Source or Program", "Table Name", "Data Element Name", "Source.Name"]]
          .pipe(to_md, index=False))
    w("")

    # --- Candidate identifiers
    name = en.str.strip()
    desc = df["Description/Definition"]
    by_name = name.str.contains(ID_PATTERN) | name.str.contains(r"(?:ID|Id|Key|Code|Number|Nbr|Num)$|_id$|_ID$", regex=True)
    by_desc = desc.str.contains(r"\b(?:unique identifier|uniquely identif|identifier|social security|ssn)\b",
                                case=False, regex=True)
    pkflag = df["Primary Key?"].str.strip().str.lower().isin(["x", "y", "?"])
    cand = df[by_name | by_desc | pkflag].assign(
        hit=lambda d: [
            ",".join(k for k, v in (("name", a), ("desc", b), ("pk", c)) if v)
            for a, b, c in zip(by_name[d.index], by_desc[d.index], pkflag[d.index])
        ])
    w(f"## Candidate identifier elements ({len(cand)} rows)\n")
    w("Matched on element name (id/key/code/number/SSN/…), description "
      "(identifier/unique/SSN), or a PK flag of x/Y/?. Grouped by normalized element name "
      "to surface identifiers that recur across tables and agencies — recurrence is a hint, "
      "not evidence of a shared key.\n")
    grp = (cand.assign(n=cand["Data Element Name"].str.strip().str.lower())
           .groupby("n")
           .agg(rows=("Row #", "size"),
                sectors=("Sector Name", lambda s: ", ".join(sorted(set(s)))),
                agencies=("Agency Name", lambda s: ", ".join(sorted(set(s)))),
                tables=("Table Name", lambda s: len(set(s))),
                pk_flags=("Primary Key?", lambda s: "".join(sorted(v.strip() for v in s if v.strip()))[:20]),
                hit=("hit", lambda s: ",".join(sorted(set(",".join(s).split(","))))))
           .sort_values(["rows", "n"], ascending=[False, True])
           .reset_index().rename(columns={"n": "element (normalized)"}))
    w(grp.pipe(to_md, index=False))
    w("")

    w("## Flagged / uncertain PK elements by table\n")
    pk = df[pkflag].assign(t=df["Table Name"].str.strip().replace("", "(blank)"))
    w(pk.groupby(["Sector Name", "Source or Program", "t"])
      .apply(lambda d: "; ".join(f"{n.strip()}[{p.strip()}]" for n, p in zip(d["Data Element Name"], d["Primary Key?"])),
             include_groups=False)
      .rename("PK elements [flag]").reset_index().rename(columns={"t": "Table Name"}).pipe(to_md, index=False))
    w("")

    (OUT / "profile.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT / 'profile.md'} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
